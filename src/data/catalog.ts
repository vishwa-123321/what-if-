export function getGenreByName(genreName: string): GenreDefinition {
  return (
    GENRES.find((g) => g.name.toLowerCase() === genreName.toLowerCase()) ||
    GENRES[0]
  );
}

export function getAvatarForKey(
  key: string | undefined,
  protagonistCustomImage?: string | null
): string {
  switch (key) {
    case 'elena':
      return ASSETS.charElena;
    case 'kaelen':
      return ASSETS.charKaelen;
    case 'nyx':
      return ASSETS.charNyx;
    case 'protagonist':
      return protagonistCustomImage || ASSETS.charElena;
    default:
      return ASSETS.charKaelen;
  }
}

export function getCoverImageForGenre(genreName: string): string {
  return getGenreByName(genreName).coverImage;
}
